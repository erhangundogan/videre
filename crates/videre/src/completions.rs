//! Shell completion scripts, generated from the same clap command the binary
//! parses with, so they cannot drift from the real flags.

use clap_complete::shells::Shell;
use std::ffi::OsStr;
#[cfg(target_os = "macos")]
use std::os::unix::ffi::OsStrExt;
use std::path::{Path, PathBuf};

/// The completion script for `shell`. The leading stamp is what the per-run
/// self-setup compares before overwriting an installed file, and what tells a
/// hand-written script apart from a generated one.
pub fn script_for(shell: Shell) -> String {
    let mut cmd = crate::cli_command();
    let mut buf = Vec::new();
    clap_complete::generate(shell, &mut cmd, "videre", &mut buf);
    let extra = if shell == Shell::Fish {
        fish_config_set_lines()
    } else {
        String::new()
    };
    format!(
        "# generated by videre {}\n{}{extra}",
        env!("CARGO_PKG_VERSION"),
        String::from_utf8_lossy(&buf)
    )
}

/// `config set <key> <value>` for fish. clap's generator writes no line for a
/// positional's values in a fish script, so the key fell back to files and
/// the value had nothing. These are plain fish rules over the same lists the
/// dynamic completer offers: the keys, and each key's fixed values.
fn fish_config_set_lines() -> String {
    let set = "__fish_videre_using_subcommand config; and __fish_seen_subcommand_from set";
    let mut out = String::from(
        "\n# config set: the key, then its value (added by videre; see completions.rs)\n\
         function __fish_videre_config_set_words\n\
         \x20   set -l words (commandline -opc)\n\
         \x20   set -l at (contains -i -- set $words); or return\n\
         \x20   # Nothing after `set` yet: [4..-1] of three words would count back.\n\
         \x20   test $at -lt (count $words); or return\n\
         \x20   printf '%s\\n' $words[(math $at + 1)..-1]\n\
         end\n\
         function __fish_videre_config_set_key\n\
         \x20   set -l words (__fish_videre_config_set_words)\n\
         \x20   test (count $words) -eq 1; and test \"$words[1]\" = \"$argv[1]\"\n\
         end\n",
    );
    out.push_str(&format!(
        "complete -c videre -n \"{set}; and test (count (__fish_videre_config_set_words)) -eq 0\" -f -a \"{}\"\n",
        crate::commands::config::CONFIG_KEYS.join(" ")
    ));
    // From the value on, nothing is a file: a number's value included.
    out.push_str(&format!(
        "complete -c videre -n \"{set}; and test (count (__fish_videre_config_set_words)) -ge 1\" -f\n"
    ));
    for key in crate::commands::config::CONFIG_KEYS {
        let values = config_values_for(key, &[]);
        if values.is_empty() {
            continue;
        }
        let words: Vec<String> = values
            .iter()
            .map(|(v, help)| match help {
                Some(h) => format!("{v}\\t'{h}'"),
                None => v.clone(),
            })
            .collect();
        out.push_str(&format!(
            "complete -c videre -n \"{set}; and __fish_videre_config_set_key {key}\" -f -a \"{}\"\n",
            words.join(" ")
        ));
    }
    out
}

